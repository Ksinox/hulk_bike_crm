/**
 * Планшет — своя раскладка (21.09, после правки заказчика).
 *
 * Как было и почему переделали. С 15.09 планшет открывал телефонный слой и
 * показывал контент колонкой 960px по центру. На 1180px это давало мёртвые
 * поля по 110px с каждой стороны, списки шли в одну колонку, а мастера
 * выглядели окном по центру с прокруткой. Заказчик (21.09): «планшетная
 * версия работает криво; это не телефонная версия, но и вроде что-то ужато».
 *
 * Правило теперь такое: **планшет — не телефон пошире и не сжатый
 * компьютер.** У него своя раскладка:
 *
 *   • контент идёт во всю ширину экрана с полями 24–28px, без колонки
 *     по центру: ширина используется, а не простаивает;
 *   • списки на планшете — в ДВЕ колонки (лёжа, где влезает, — в три):
 *     строка во всю ширину 1180px не читается, потому что имя у левого края,
 *     а сумма у правого — именно от этого и спасала колонка 960px;
 *   • мастера и карточки — полноэкранные, шаги в две колонки, действие
 *     внизу справа, без прокрутки там, где контент помещается;
 *   • размеры крупнее телефонных: тач-таргет ≥48px, поля карточек 20–24px.
 *
 * Классы — литералы: Tailwind находит их в исходниках. Брейкпоинты `tab:`
 * (от 768px) и `tabw:` (от 1100px) заданы в tailwind.config.ts.
 */

