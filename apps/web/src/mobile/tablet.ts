/**
 * Планшет в телефонном слое (15.09).
 *
 * С 15.09 iPad и Android-планшет открывают телефонный слой при любой ширине
 * («планшетная версия ближе к мобильной»). На 1180–1366px строка списка во
 * всю ширину не читается: имя у левого края, сумма у правого. Поэтому
 * контент стоит колонкой по центру. На телефоне эти классы ничего не меняют.
 *
 * Классы — литералы: Tailwind находит их в исходниках. Ширину 960px меняй
 * во всех строках разом (и у кнопки «+» в MobileApp). Нижние листы
 * (BottomSheet, «Ещё», шторка ui.tsx) — не шире 640px, цифровая
 * клавиатура — 520px.
 */

/** Колонка контента: обёртка с mx-auto w-full. */
export const TABLET_COLUMN = "max-w-[960px]";

/**
 * Боковые поля прокручиваемого экрана: 12px на телефоне, на планшете — до
 * колонки по центру. Скролл-контейнер остаётся во всю ширину, поэтому
 * листать можно и пальцем по полям.
 */
export const TABLET_PAD_X = "px-[max(0.75rem,calc((100%_-_960px)/2_+_0.75rem))]";

/** То же для 16px полей (формы, списки главной оболочки). */
export const TABLET_PAD_X_4 = "px-[max(1rem,calc((100%_-_960px)/2_+_1rem))]";

/** Шапка полноэкранного экрана: кнопка «назад» стоит у края колонки. */
export const TABLET_PAD_X_HEADER = "px-[max(0.5rem,calc((100%_-_960px)/2_+_0.25rem))]";

/**
 * Полноэкранный мастер (оплата, завершение, ущерб, замена, приёмка). Корень
 * мастера на широком экране (lg, от 1024px) становится затемнением,
 * а эта панель — колонкой по центру. Без transform: вложенные fixed-листы
 * (цифровая клавиатура, «простить просрочку») остаются привязаны к экрану.
 */
export const TABLET_WIZARD_PANEL =
  "flex min-h-0 w-full flex-1 flex-col bg-surface lg:max-w-[760px] lg:shadow-card-lg";
