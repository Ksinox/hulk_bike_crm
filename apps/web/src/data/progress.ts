/**
 * Раздел «Развитие» — план улучшений CRM на период и статус по каждому пункту.
 *
 * Источник — согласованный список задач заказчика. Текст пунктов приводится
 * как прислан (поле `quote`), чтобы заказчик узнавал свои формулировки.
 *
 * Статусы обновляются вручную по мере работы:
 *   planned → in_progress → done (проверено разработкой) → accepted (принято)
 *
 * Скриншоты «было/стало» добавляются в `shots` после приёмки пункта —
 * файлы лежат в `apps/web/public/progress/`.
 */

export type ProgressStatus = "planned" | "in_progress" | "done" | "accepted";

export type ProgressShot = {
  /** Путь к картинке «было» (из public/, напр. "/progress/9-before.png"). */
  before?: string;
  /** Путь к картинке «стало». */
  after?: string;
  /** Подпись к паре скриншотов. */
  caption?: string;
};

/** Картинка шага истории: общий план или крупный кроп. */
export type StoryImage = {
  src: string;
  /** Подпись под миниатюрой («общий план», «крупно» и т.п.). */
  label?: string;
};

/**
 * Шаг пошаговой истории пункта — «заходим сюда → жмём это → вот проблема →
 * вот как стало». Погружает читателя, который о проблеме не знал.
 */
export type ProgressStep = {
  /** Окраска шага: обычный / проблема (красный) / после исправления (зелёный). */
  tag?: "bug" | "fix";
  text: string;
  imgs?: StoryImage[];
};

export type ProgressItem = {
  /** Номер пункта: "1".."24" или "Б1".."Б5". */
  id: string;
  /** Ключ группы. */
  group: string;
  /** Короткий заголовок — что делаем. */
  title: string;
  /** Текст заказчика как прислан. */
  quote?: string;
  status: ProgressStatus;
  /** Пояснение от разработки (что именно сделано / что уточняется). */
  note?: string;
  shots?: ProgressShot[];
  /** Пошаговая история со скриншотами (главный формат подачи). */
  story?: ProgressStep[];
};

export type ProgressGroup = {
  key: string;
  title: string;
  /** Короткое пояснение группы. */
  hint?: string;
};

