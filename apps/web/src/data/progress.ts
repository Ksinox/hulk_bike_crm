/** Сводка по статусам — для прогресс-бара и чипов. */
export function progressSummary(items: ProgressItem[] = progressItems) {
  const total = items.length;
  const by = (s: ProgressStatus) => items.filter((i) => i.status === s).length;
  const accepted = by("accepted");
  const done = by("done");
  const inProgress = by("in_progress");
  const planned = by("planned");
  // Готовность: принятые = 100 %, проверенные разработкой = 70 %,
  // в работе = 30 % — чтобы полоса двигалась по ходу дела, а не рывком.
  const weighted = accepted + done * 0.7 + inProgress * 0.3;
  const percent = total > 0 ? Math.round((weighted / total) * 100) : 0;
  return { total, accepted, done, inProgress, planned, percent };
}
